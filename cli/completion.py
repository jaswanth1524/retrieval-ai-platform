"""Shell completion for ``docrag``, written from its own argument parser.

    docrag completion bash > ~/.local/share/bash-completion/completions/docrag
    docrag completion zsh  > "${fpath[1]}/_docrag"     # or: eval "$(docrag completion zsh)"

Generated rather than hand-written, so a new command or flag completes as soon as it
exists; no extra dependency (argcomplete would add one and run Python on every Tab).
Completes commands, their flags and the choices a flag takes; files are left to the
shell's own completion.
"""

from __future__ import annotations

import argparse
import shlex


def _subparsers(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:  # noqa: SLF001 - argparse has no public walk
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            return dict(action.choices)
    return {}


def _flags(parser: argparse.ArgumentParser) -> list[str]:
    return sorted(
        option
        for action in parser._actions  # noqa: SLF001
        for option in action.option_strings
        if option.startswith("--")
    )


def _choices(parser: argparse.ArgumentParser) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for action in parser._actions:  # noqa: SLF001
        if action.choices and action.option_strings:
            for option in action.option_strings:
                found[option] = [str(choice) for choice in action.choices]
    return found


def _positional_choices(parser: argparse.ArgumentParser) -> list[str]:
    return sorted(
        str(choice)
        for action in parser._actions  # noqa: SLF001
        if not action.option_strings
        and action.choices
        and not isinstance(action, argparse._SubParsersAction)  # noqa: SLF001
        for choice in action.choices
    )


def completion_script(parser: argparse.ArgumentParser, shell: str) -> str:
    """A bash completion function (zsh loads it through ``bashcompinit``)."""

    commands = _subparsers(parser)
    top_words = shlex.quote(" ".join([*sorted(commands), *_flags(parser)]))
    # Global flags that take a value: the word after one isn't the command.
    value_flags = "|".join(
        sorted(
            option
            for action in parser._actions  # noqa: SLF001
            if action.nargs != 0 and action.option_strings
            for option in action.option_strings
            if option.startswith("--")
        )
    )
    cases = []
    for name, sub in sorted(commands.items()):
        words = " ".join([*_positional_choices(sub), *_flags(sub)])
        choice_cases = "".join(
            f"      {shlex.quote(option)}) "
            f'COMPREPLY=($(compgen -W {shlex.quote(" ".join(values))} -- "$cur")); return ;;\n'
            for option, values in sorted(_choices(sub).items())
        )
        nested = _subparsers(sub)
        nested_words = " ".join(sorted(nested))
        cases.append(
            f"    {shlex.quote(name)})\n"
            f'      case "$prev" in\n{choice_cases}      esac\n'
            + (
                f'      if [ "$COMP_CWORD" -eq $((cmd_index + 1)) ]; then '
                f'COMPREPLY=($(compgen -W {shlex.quote(nested_words)} -- "$cur")); return; fi\n'
                if nested
                else ""
            )
            + f'      COMPREPLY=($(compgen -W {shlex.quote(words)} -- "$cur"))\n'
            "      [ ${#COMPREPLY[@]} -eq 0 ] && compopt -o default 2>/dev/null\n"
            "      ;;\n"
        )
    body = f"""# docrag shell completion ({shell}); generated by `docrag completion {shell}`.
_docrag() {{
  local cur prev cmd="" cmd_index=0 i
  cur="${{COMP_WORDS[COMP_CWORD]}}"
  prev="${{COMP_WORDS[COMP_CWORD-1]}}"
  for ((i = 1; i < COMP_CWORD; i++)); do
    case "${{COMP_WORDS[i]}}" in
      {value_flags}) i=$((i + 1)) ;;
      -*) ;;
      *) cmd="${{COMP_WORDS[i]}}"; cmd_index=$i; break ;;
    esac
  done
  if [ -z "$cmd" ]; then
    COMPREPLY=($(compgen -W {top_words} -- "$cur"))
    return
  fi
  case "$cmd" in
{"".join(cases)}  esac
}}
complete -F _docrag docrag
"""
    if shell == "zsh":
        return (
            "(( $+functions[compdef] )) || { autoload -U +X compinit && compinit; }\n"
            "autoload -U +X bashcompinit && bashcompinit\n" + body
        )
    return body
